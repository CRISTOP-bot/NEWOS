#!/usr/bin/env bash
# pack-sdk.sh: turn the generated NEWOS sysroot into one `.new` package.
#
# The image embeds the result at /tmp so a user can install the C SDK into
# the running (RAM) filesystem and compile/link against it with the on-board
# TinyCC:
#
#   newpkg install /tmp/newos-sdk-<version>-x86_64.new
#   tcc -static -nostdlib -I/usr/lib/tcc/include -I/usr/include \
#       -o /tmp/hello /usr/lib/crt0.o hello.c /usr/lib/libnsh.a /usr/lib/libc.a
#
# Contents: libc headers + newos/syscall_abi.h, libc.a/libnsh.a, crt0.o,
# app.ld, TinyCC's own include/ (stdarg.h, stddef.h, ...) under
# /usr/lib/tcc/include -- where CONFIG_TCCDIR points -- and TinyCC's runtime
# helpers (libtcc1.a) under /usr/lib/tcc/.
#
#   scripts/pack-sdk.sh [sysroot] [outfile] [version]
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
SYSROOT=$(realpath -m "${1:-$ROOT/sysroot}")
VER="${3:-$(cat "$ROOT/VERSION")}"
OUT=$(realpath -m "${2:-$ROOT/build/packages/newos-sdk-$VER-x86_64.new}")
TCC_INC="$ROOT/ports/tcc/src/include"

[ -d "$SYSROOT/usr/include" ] || {
    echo "pack-sdk: no sysroot at $SYSROOT (run 'make sdk')" >&2
    exit 1
}
[ -d "$TCC_INC" ] || { echo "pack-sdk: missing $TCC_INC" >&2; exit 1; }

MANIFEST=$(mktemp)
SPEC=$(mktemp)
trap 'rm -f "$MANIFEST" "$SPEC"' EXIT

# One "host-src vfs-dst mode" line per file.
find "$SYSROOT/usr/include" -type f | while read -r f; do
    echo "$f ${f#"$SYSROOT"} 0644"
done > "$MANIFEST"
for f in libc.a libnsh.a crt0.o app.ld; do
    [ -f "$SYSROOT/usr/lib/$f" ] && echo "$SYSROOT/usr/lib/$f /usr/lib/$f 0644"
done >> "$MANIFEST"
for f in "$TCC_INC"/*.h; do
    [ -f "$f" ] && echo "$f /usr/lib/tcc/include/$(basename "$f") 0644"
done >> "$MANIFEST"
# tcc's own crt/runtime archive. Without it every `tcc file.c -o file` link
# stops at "file 'libtcc1.a' not found" (64-bit division, varargs helpers).
TCC_LIB1="$ROOT/ports/tcc/libtcc1.a"
[ -f "$TCC_LIB1" ] && echo "$TCC_LIB1 /usr/lib/tcc/libtcc1.a 0644" >> "$MANIFEST"

{
    echo "# generated by scripts/pack-sdk.sh - do not edit"
    echo "name = \"newos-sdk\""
    echo "version = \"$VER\""
    echo "arch = \"x86_64\""
    echo "desc = \"NEWOS C SDK (libc headers, libc.a, crt0.o) for /bin/tcc\""
    echo "license = \"MIT\""
    echo "maintainer = \"NEWOS\""
    echo "build = \"make sdk-pkg\""
    echo "newos-min = \"0.2.0\""
    echo "depends = \"\""
    echo ""
    echo "files:"
    sort -k2 "$MANIFEST"
} > "$SPEC"

mkdir -p "$(dirname "$OUT")"
python3 "$ROOT/tools/newpkg/newpkg-build.py" "$SPEC" -o "$OUT" --root /
echo "pack-sdk: $(basename "$OUT") ($(stat -c %s "$OUT") bytes)"
