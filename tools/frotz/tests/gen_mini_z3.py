#!/usr/bin/env python3
"""Generate tools/frotz/tests/mini.z3, a minimal but valid Z-machine v3
story used by the NEWOS frotz port tests and shipped as
/usr/share/zcode/mini.z3 demo story.

The program is intentionally tiny: it prints a banner, does one line
read (exercising os_read_line), prints a second banner and quits:

    print "frotz mini demo works"
    new_line
    read text parse          (v3 sread, 0xE4)
    print "read ok"
    new_line
    quit

Opcode numbers were cross-checked against the ported interpreter's
dispatch tables in userland/user/programs/frotz/process.c:
  0OP  0xB2 print, 0xB3 print_ret, 0xBB new_line, 0xBA quit
  VAR  0xE4 read (operands: text buffer addr, parse buffer addr)

Layout (byte addresses in the story image):
  0x040 code (initial PC), inline ZSCII strings
  0x080 globals (240 words)
  0x260 text input buffer (62 bytes; text[0] = max chars)
  0x2A0 parse input buffer (16 bytes)
  0x2C0 static memory base
  0x2C0 dictionary (no separators, entry length 4, zero entries)
  0x2E0 object table: defaults, object "room" (global 0 = object 1)

The generated bytes are deterministic and committed next to this
script; run it again only to (re)generate.

Usage: python3 gen_mini_z3.py [out-file]
"""

import sys

# Z-machine default alphabet A0 (codes 6..31): a..z.  Digits live in A1;
# the demo strings stick to A0 plus space so no shifting is needed.
A0 = {ch: code for code, ch in enumerate(
    "abcdefghijklmnopqrstuvwxyz", start=6)}
A0[" "] = 0


def encode_string(s):
    """5-bit packed ZSCII text, little-endian words, top bit on the last."""
    code = [A0[ch] for ch in s]
    while len(code) % 3:  # pad to a whole number of 3-char groups
        code.append(5)    # 'shift-to-A2' pad char, harmless filler
    words = []
    for i in range(0, len(code), 3):
        a, b, c = code[i:i + 3]
        words.append((a << 10) | (b << 5) | c)
    words[-1] |= 0x8000
    for w in words:
        assert 0 <= w <= 0xFFFF
    return b"".join(w.to_bytes(2, "big") for w in words)


def main():
    text_buf = 0x0260
    parse_buf = 0x02A0
    globals_addr = 0x0080
    dictionary_addr = 0x02C0
    static_base = 0x02C0
    himem_base = 0x02C0
    objects_addr = 0x02E0

    # --- program -------------------------------------------------------
    program = b""
    program += b"\xb2"                      # print (literal follows)
    program += encode_string("frotz mini demo works")
    program += b"\xbb"                      # new_line
    # VAR read 0xE4, specifier 00 00 11 11 = 0x0f (two word constants),
    # operands: text buffer, parse buffer.
    program += b"\xe4\x0f"
    program += text_buf.to_bytes(2, "big")
    program += parse_buf.to_bytes(2, "big")
    program += b"\xb2"                      # print (literal follows)
    program += encode_string("read ok")
    program += b"\xbb"                      # new_line
    program += b"\xba"                      # quit

    init_pc = 0x040
    assert init_pc + len(program) <= globals_addr

    # --- fixed layout image --------------------------------------------
    image = bytearray(0x0400)
    image[init_pc:init_pc + len(program)] = program

    # text buffer: text[0] = maximum chars the interpreter may store
    image[text_buf] = 0x30
    # parse buffer: parse[0] = maximum words the parser may store
    image[parse_buf] = 10

    # dictionary: 0 separators, entry length 4, 0 entries
    image[dictionary_addr:dictionary_addr + 4] = b"\x00\x04\x00\x00"

    # object table: 31 property defaults (zeros), then object 1 with
    # clear attributes, no relatives, property table holding a short
    # name.  Object 1 is "room": the interpreter draws a V3 status line
    # on every read, using global 0 as the location object.
    objects = bytearray(31 * 2)             # defaults
    obj1_ptr = objects_addr + len(objects)
    prop_table_ptr = obj1_ptr + 9
    name = encode_string("room")
    # frotz 2.44 v1-3 convention: props[0] = short name length in WORDS
    # (a byte), then the encoded name, then the 0x00 property terminator.
    props = bytearray(bytes((len(name) // 2,)) + name + b"\x00")
    obj1 = bytearray(b"\x00\x00\x00\x00"    # attributes
                     + bytes(3)             # parent, sibling, child
                     + prop_table_ptr.to_bytes(2, "big"))
    image[objects_addr:objects_addr + len(objects)] = objects
    image[obj1_ptr:obj1_ptr + len(obj1)] = obj1
    image[prop_table_ptr:prop_table_ptr + len(props)] = props
    prop_end = prop_table_ptr + len(props)
    assert prop_end <= len(image)

    # global 0 (variable 0x10): the location object for the V3 status line
    image[globals_addr:globals_addr + 2] = (1).to_bytes(2, "big")

    # --- header ---------------------------------------------------------
    file_len = len(image)
    assert file_len % 2 == 0
    hdr = bytearray(0x40)
    hdr[0] = 3                                          # version
    hdr[1:3] = (0).to_bytes(2, "big")                # flags
    hdr[2:4] = (1).to_bytes(2, "big")                # release
    hdr[4:6] = himem_base.to_bytes(2, "big")         # high memory base
    hdr[6:8] = init_pc.to_bytes(2, "big")            # initial PC
    hdr[8:10] = dictionary_addr.to_bytes(2, "big")   # dictionary
    hdr[10:12] = objects_addr.to_bytes(2, "big")     # objects
    hdr[12:14] = globals_addr.to_bytes(2, "big")     # globals
    hdr[14:16] = static_base.to_bytes(2, "big")      # static memory base
    hdr[16:18] = (0).to_bytes(2, "big")              # flags 2
    hdr[18:24] = b"NEW000"                              # serial
    hdr[24:26] = (0).to_bytes(2, "big")              # abbreviations
    hdr[26:28] = (file_len // 2).to_bytes(2, "big")  # length / 2 (v3+)
    checksum = sum(image[0x40:]) & 0xFFFF
    hdr[28:30] = checksum.to_bytes(2, "big")         # checksum
    hdr[30] = ord("F")                                  # interpreter version
    hdr[31] = 4                                         # interpreter number
    hdr[32] = 24                                        # screen rows
    hdr[33] = 75                                        # screen columns
    hdr[36] = 2                                         # default bg
    hdr[37] = 2                                         # default fg
    image[0:0x40] = hdr

    out = sys.argv[1] if len(sys.argv) > 1 else "mini.z3"
    with open(out, "wb") as fp:
        fp.write(image)
    print(f"wrote {out}: {file_len} bytes, checksum 0x{checksum:04x}")


if __name__ == "__main__":
    main()
